# Gram-parameterized SOS objects (used to build multipliers/localizers)
# ======================================================================
def sos_poly_variable(nvars, basis):
    """An SOS polynomial "variable" ``s(x) = z(x)' Q z(x)`` with Q PSD.

    Returns ``(s, Q)`` where ``s`` is a Polynomial whose coefficients are
    affine in the entries of the PSD CVXPY variable ``Q`` (so ``s`` is SOS by
    construction and needs no extra constraint).
    """
    S, Q = sos_matrix_variable(nvars, 1, basis)
    return S[0, 0], Q


def sos_matrix_variable(nvars, size, basis):
    """An SOS-matrix "variable" of the given size over an x-monomial basis.

    Returns ``(S, Q)``: ``S`` is a ``size x size`` object array of Polynomials
    with ``S(x) = (z(x) kron I)' Q (z(x) kron I)`` for the PSD CVXPY variable
    ``Q``; it is an SOS matrix by construction.
    """
    basis = [tuple(b) for b in basis]
    nB = len(basis)
    if nB == 0:
        raise ValueError("empty basis")
    N = size * nB
    Q = cp.Variable((N, N), PSD=True)
    terms = [[defaultdict(list) for _ in range(size)] for _ in range(size)]
    for a, b in product(range(nB), repeat=2):
        gamma = tuple(x + y for x, y in zip(basis[a], basis[b]))
        for i in range(size):
            for j in range(i, size):
                terms[i][j][gamma].append(Q[a * size + i, b * size + j])
    S = np.empty((size, size), dtype=object)
    for i in range(size):
        for j in range(i, size):
            S[i, j] = Polynomial(
                nvars, {g: sum(lst) for g, lst in terms[i][j].items()}
            )
            S[j, i] = S[i, j]
    return S, Q


