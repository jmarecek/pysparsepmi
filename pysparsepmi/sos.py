"""CVXPY-style modelling of (sparse) sum-of-squares constraints.

The public API mirrors CVXPY's LMI interface: ``P >> 0`` on a
:class:`PolyMatrix` (or a scalar :class:`~pysparsepmi.polynomial.Polynomial`)
creates a constraint object, and :class:`Problem` couples an ordinary CVXPY
objective with a list of such constraints::

    import cvxpy as cp
    import pysparsepmi as psp

    x, = psp.polyvar(1)
    t = cp.Variable()
    F = psp.PolyMatrix([[1 + x**2, x], [x, 1]])
    prob = psp.Problem(cp.Maximize(t), [F - psp.eye(2, nvars=1) * t >> 0])
    prob.solve(solver="SCS")

``P >> 0`` is interpreted as "P admits a sum-of-squares certificate":

* for a scalar polynomial, a Gram (SOS) decomposition whose monomial basis is
  split across the maximal cliques of the correlative sparsity pattern of the
  variables — the behaviour of YALMIP's ``sos.csp`` option;
* for a polynomial matrix, the chordal decomposition
  ``P = sum_k E_k' S_k(x) E_k`` of Zheng & Fantuzzi (2020), with one SOS
  matrix ``S_k`` per maximal clique of the (chordally extended) sparsity
  pattern of ``P``.

Both reduce to the classical dense SOS constraint when ``sparse=False``.
"""
