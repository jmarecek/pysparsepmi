class SOSInfeasibleError(ValueError):
    """Raised when an SOS constraint is structurally infeasible.

    This happens when a monomial with a nonzero numeric coefficient cannot be
    generated by any product of Gram-basis monomials (e.g. an odd maximal
    degree, or a term excluded by the sparsity pattern).
    """


# ======================================================================
# Polynomial matrices
# ======================================================================
class PolyMatrix:
    """A square symmetric matrix of polynomials, supporting ``P >> 0``.

    Entries may be polynomials, numbers, or scalar CVXPY expressions.
    Arithmetic (+, -, scalar *, @) is supported, mirroring how CVXPY
    expressions combine before being turned into constraints with ``>>``.
    """

    __array_ufunc__ = None
    __array_priority__ = 2000.0

    def __init__(self, data, nvars=None):
        if isinstance(data, PolyMatrix):
            self.arr = data.arr.copy()
        else:
            self.arr = poly_matrix(data, nvars)
        self.nvars = self.arr[0, 0].nvars

    @property
    def shape(self):
        return self.arr.shape

    def __getitem__(self, idx):
        out = self.arr[idx]
        if isinstance(out, np.ndarray):
            return PolyMatrix(out)
        return out

    # -- arithmetic ----------------------------------------------------
    def _other_arr(self, other):
        if isinstance(other, PolyMatrix):
            return other.arr
        if isinstance(other, (list, tuple, np.ndarray)):
            return poly_matrix(other, self.nvars)
        return None

    def __add__(self, other):
        arr = self._other_arr(other)
        if arr is None:
            return NotImplemented
        if arr.shape != self.arr.shape:
            raise ValueError("shape mismatch in PolyMatrix addition")
        return PolyMatrix(self.arr + arr)

    __radd__ = __add__

    def __sub__(self, other):
        arr = self._other_arr(other)
        if arr is None:
            return NotImplemented
        return PolyMatrix(self.arr - arr)

    def __rsub__(self, other):
        arr = self._other_arr(other)
        if arr is None:
            return NotImplemented
        return PolyMatrix(arr - self.arr)

    def __mul__(self, other):
        # scalar multiplication only (number, Polynomial, or CVXPY scalar)
        if isinstance(other, (Polynomial,)) or _is_number(other) or _is_scalar_expression(other):
            out = np.empty(self.arr.shape, dtype=object)
            for idx in np.ndindex(self.arr.shape):
                out[idx] = self.arr[idx] * other
            return PolyMatrix(out)
        return NotImplemented

    __rmul__ = __mul__

    def __neg__(self):
        return self * (-1.0)

    def __matmul__(self, other):
        arr = self._other_arr(other)
        if arr is None:
            return NotImplemented
        m = self.arr.shape[0]
        out = np.empty((m, arr.shape[1]), dtype=object)
        for i in range(m):
            for j in range(arr.shape[1]):
                s = Polynomial.zero(self.nvars)
                for k in range(arr.shape[0]):
                    s = s + self.arr[i, k] * arr[k, j]
                out[i, j] = s
        return PolyMatrix(out)

    # -- LMI-style constraint creation ----------------------------------
    def __rshift__(self, other):
        """``P >> other``: P - other admits a sparse SOS-matrix certificate."""
        return SOSMatrix(self._shift_diff(other, right=True))

    def __lshift__(self, other):
        """``P << other``: other - P admits a sparse SOS-matrix certificate."""
        return SOSMatrix(self._shift_diff(other, right=False))

    def _shift_diff(self, other, right):
        if _is_number(other) and other == 0:
            diff = self
        else:
            arr = self._other_arr(other)
            if arr is None:
                raise TypeError("cannot compare PolyMatrix with %r" % (other,))
            diff = PolyMatrix(self.arr - arr)
        return diff if right else -diff

    def __repr__(self):
        return "PolyMatrix(%dx%d, nvars=%d)" % (
            self.shape[0],
            self.shape[1],
            self.nvars,
        )


def eye(m, nvars):
    """The m-by-m identity as a :class:`PolyMatrix` in ``nvars`` variables."""
    arr = np.empty((m, m), dtype=object)
    for i in range(m):
        for j in range(m):
            arr[i, j] = Polynomial.constant(nvars, 1.0 if i == j else 0.0)
    return PolyMatrix(arr)


