# Compilation to CVXPY constraints
# ======================================================================
def _match_coefficients(lhs, rhs_poly_terms, context):
    """Equate Gram-expansion coefficients with polynomial coefficients.

    ``lhs`` maps exponent tuples to lists of CVXPY scalar expressions;
    ``rhs_poly_terms`` maps exponent tuples to numeric or CVXPY coefficients.
    """
    constraints = []
    for gamma in set(lhs) | set(rhs_poly_terms):
        exprs = lhs.get(gamma)
        rhs = rhs_poly_terms.get(gamma, 0.0)
        if exprs:
            constraints.append(sum(exprs) == rhs)
        elif _is_number(rhs):
            if rhs != 0:
                raise SOSInfeasibleError(
                    "%s: monomial %r (coefficient %r) cannot be generated by "
                    "the Gram basis; the constraint is infeasible" % (context, gamma, rhs)
                )
        else:
            constraints.append(rhs == 0)
    return constraints


def _compile_sos(con):
    p = con.poly
    if not isinstance(p, Polynomial):
        raise TypeError("SOS expects a Polynomial")
    supp = list(p.terms)
    if not supp:
        con.cliques, con.bases, con.grams = [], [], []
        return []

    nvars = p.nvars
    if con.cliques is None:
        if con.sparse:
            _, con.cliques = correlative_sparsity(supp, nvars)
        else:
            con.cliques = [list(range(nvars))]

    bases = [gram_candidates(supp, nvars, vars=c) for c in con.cliques]
    con.bases = reduce_bases(bases, supp)

    lhs = defaultdict(list)
    con.grams = []
    con.blocks = []
    numeric_supp = set(supp)
    for B in con.bases:
        if not B:
            con.grams.append(None)
            continue
        if con.ts:
            blocks, _ = ts_matrix_blocks(
                {(0, 0): numeric_supp}, [B], method=con.ts, max_steps=con.ts_order
            )
            block_bases = [[alpha for _, alpha in blk] for blk in blocks]
        else:
            block_bases = [B]
        for BB in block_bases:
            con.blocks.append(BB)
            Q = cp.Variable((len(BB), len(BB)), PSD=True)
            con.grams.append(Q)
            for a in range(len(BB)):
                for b in range(a, len(BB)):
                    gamma = tuple(x + y for x, y in zip(BB[a], BB[b]))
                    lhs[gamma].append(Q[a, b] if a == b else 2 * Q[a, b])
    return _match_coefficients(lhs, p.terms, "SOS")


def _compile_sos_matrix(con):
    P = con.P.arr
    m = P.shape[0]
    nvars = con.P.nvars

    if con.nu:
        w = ball_multiplier(nvars, con.nu)
        P = np.array(
            [[P[i, j] * w for j in range(m)] for i in range(m)], dtype=object
        )

    # symmetry check on numeric entries
    for i in range(m):
        for j in range(i + 1, m):
            if P[i, j].is_numeric() and P[j, i].is_numeric():
                if not P[i, j].equals(P[j, i]):
                    raise ValueError(
                        "PolyMatrix is not symmetric at entry (%d, %d)" % (i, j)
                    )

    if m == 1 and con.cliques is None:
        # scalar case: fall back to correlative (variable) sparsity
        inner = SOS(P[0, 0], sparse=con.sparse, ts=con.ts, ts_order=con.ts_order)
        out = inner.compile()
        con.cliques = [[0]]
        con.bases, con.grams, con.blocks = inner.bases, inner.grams, inner.blocks
        return out

    nonzero = [(i, j) for i in range(m) for j in range(m) if not P[i, j].is_zero()]
    if con.cliques is None:
        if con.sparse:
            pattern = np.zeros((m, m), dtype=int)
            for i, j in nonzero:
                pattern[i, j] = 1
            np.fill_diagonal(pattern, 1)
            con.cliques = chordal_cliques(pattern)
        else:
            con.cliques = [list(range(m))]

    covered = set()
    for C in con.cliques:
        covered.update(product(C, C))
    for i, j in nonzero:
        if (i, j) not in covered:
            raise ValueError(
                "cliques do not cover the nonzero entry (%d, %d) of the matrix"
                % (i, j)
            )

    # union of diagonal supports (used for degree bounds and basis reduction:
    # the extremal parts of the diagonal of an SOS matrix cannot cancel)
    diag_supp_all = set()
    for i in range(m):
        diag_supp_all.update(P[i, i].terms)

    bases = []
    for C in con.cliques:
        diag_supp = set()
        for i in C:
            diag_supp.update(P[i, i].terms)
        bases.append(gram_candidates(diag_supp, nvars))
    con.bases = reduce_bases(bases, diag_supp_all)

    lhs = {}  # (i, j) i<=j -> {gamma: [exprs]}
    con.grams = []
    con.blocks = []
    for C, B in zip(con.cliques, con.bases):
        mk, nB = len(C), len(B)
        if nB == 0:
            con.grams.append(None)
            continue
        if con.ts:
            supports = {}
            for ii in range(mk):
                for jj in range(ii, mk):
                    supports[(ii, jj)] = set(P[C[ii], C[jj]].terms)
            blocks, _ = ts_matrix_blocks(
                supports, [B] * mk, method=con.ts, max_steps=con.ts_order
            )
            for blk in blocks:
                con.blocks.append([(C[ii], alpha) for ii, alpha in blk])
                nblk = len(blk)
                Q = cp.Variable((nblk, nblk), PSD=True)
                con.grams.append(Q)
                # ordered node pairs with row(a) <= row(b) fill the upper
                # triangle of sum_k E_k' S_k E_k, exactly as the dense loop
                for a in range(nblk):
                    ii, alpha = blk[a]
                    for b in range(nblk):
                        jj, beta = blk[b]
                        if C[ii] > C[jj]:
                            continue
                        dest = lhs.setdefault((C[ii], C[jj]), defaultdict(list))
                        gamma = tuple(x + y for x, y in zip(alpha, beta))
                        dest[gamma].append(Q[a, b])
            continue
        Q = cp.Variable((mk * nB, mk * nB), PSD=True)
        con.grams.append(Q)
        # S_k(x)[ii, jj] = sum_{a,b} Q[a*mk+ii, b*mk+jj] * z_a(x) * z_b(x)
        for ii in range(mk):
            for jj in range(ii, mk):
                key = (C[ii], C[jj])
                dest = lhs.setdefault(key, defaultdict(list))
                for a in range(nB):
                    for b in range(nB):
                        gamma = tuple(x + y for x, y in zip(B[a], B[b]))
                        dest[gamma].append(Q[a * mk + ii, b * mk + jj])

    constraints = []
    entries = set(lhs) | {(i, j) for i, j in nonzero if i <= j}
    for i, j in sorted(entries):
        constraints.extend(
            _match_coefficients(
                lhs.get((i, j), {}), P[i, j].terms, "SOSMatrix entry (%d, %d)" % (i, j)
            )
        )
    return constraints


# ======================================================================
# Problem
# ======================================================================
class Problem:
    """Couples a CVXPY objective with (sparse) SOS constraints.

    Mirrors ``cvxpy.Problem``: ``objective`` is a ``cvxpy.Minimize`` /
    ``cvxpy.Maximize`` over CVXPY decision variables (or ``None`` for a
    feasibility problem), and ``constraints`` may mix :class:`SOS` /
    :class:`SOSMatrix` objects (e.g. created with ``>>``) with ordinary CVXPY
    constraints.
    """

    def __init__(self, objective=None, constraints=()):
        self.objective = objective
        self.constraints = list(constraints)
        self._cvxpy_problem = None
        self.status = None
        self.value = None

    def compile(self):
        """Build (and cache) the underlying ``cvxpy.Problem``."""
        if self._cvxpy_problem is None:
            cons = []
            for c in self.constraints:
                if isinstance(c, (SOS, SOSMatrix)):
                    cons.extend(c.compile())
                else:
                    cons.append(c)
            obj = self.objective if self.objective is not None else cp.Minimize(0)
            self._cvxpy_problem = cp.Problem(obj, cons)
        return self._cvxpy_problem

    def solve(self, solver="SCS", verbose=False, **kwargs):
        prob = self.compile()
        prob.solve(solver=solver, verbose=verbose, **kwargs)
        self.status = prob.status
        self.value = prob.value
        return self.value
